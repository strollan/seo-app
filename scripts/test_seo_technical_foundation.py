"""
Regression tests for the technical SEO foundation: unique per-page
metadata (title/description/canonical/robots/Open-Graph/Twitter) for the
three public indexable pages (/, /lead-bot, /compare), homepage
Organization + WebSite JSON-LD, the noindex response header applied to
every non-public route via app.seo_meta.should_apply_noindex_header(),
and /robots.txt + /sitemap.xml.

All metadata is generated by app.seo_meta -- a single reusable module --
rather than duplicated across the two Jinja templates (index.html,
compare.html) and the hand-built HTML string in
agents/lead_dashboard_agent.py's render_lead_dashboard(). These tests
exercise the real rendered output via FastAPI's TestClient, not just the
seo_meta module in isolation, so a future edit that breaks the wiring
(not just the content) will be caught.

Does not touch Lead Finder scanning, DataForSEO, scoring, exports, guest
limits, or CSRF behavior -- purely additive metadata/markup and a response
header.
"""

