class HomepageJsonLdTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.client = TestClient(appmain.app)

    def test_homepage_has_organization_and_website_jsonld(self):
        import json

        body = self.client.get("/").text
        scripts = re.findall(
            r'<script type="application/ld\+json">(.*?)</script>', body, re.DOTALL
        )
        self.assertEqual(len(scripts), 2)

        types = set()
        for raw in scripts:
            data = json.loads(raw)
            self.assertEqual(data["@context"], "https://schema.org")
            self.assertEqual(data["name"], "LeadMeLeads")
            self.assertEqual(data["url"], "https://leadmeleads.com")
            types.add(data["@type"])

        self.assertEqual(types, {"Organization", "WebSite"})

    def test_homepage_jsonld_has_no_search_action(self):
        body = self.client.get("/").text
        self.assertNotIn("SearchAction", body)

    def test_homepage_jsonld_has_no_unverifiable_claims(self):
        body = self.client.get("/").text
        scripts = re.findall(
            r'<script type="application/ld\+json">(.*?)</script>', body, re.DOTALL
        )
        jsonld_text = " ".join(scripts)
        for forbidden in [
            "aggregateRating",
            "reviewCount",
            "ratingValue",
            "priceRange",
            "foundingDate",
            "sameAs",
            "potentialAction",
        ]:
            self.assertNotIn(forbidden, jsonld_text)

    def test_other_public_pages_do_not_duplicate_homepage_jsonld(self):
        for path in ["/lead-bot", "/compare"]:
            with self.subTest(path=path):
                body = self.client.get(path).text
                self.assertNotIn("application/ld+json", body)


class NoindexPrivateRouteTests(unittest.TestCase):
    """Every non-public route must carry X-Robots-Tag: noindex, nofollow,
    regardless of auth state or response status (redirect, 200, 401,
    etc.) -- the middleware applies unconditionally to non-public paths."""

    @classmethod
    def setUpClass(cls):
        cls.client = TestClient(appmain.app)

    PRIVATE_PATHS = [
        "/login",
        "/create-account",
        "/forgot-password",
        "/settings",
        "/history",
        "/analyze",
        "/lead-bot/run",
        "/lead-bot/csrf-token",
        "/api/find-competitors",
    ]

    def test_private_routes_carry_noindex_header(self):
        for path in self.PRIVATE_PATHS:
            with self.subTest(path=path):
                response = self.client.get(path, follow_redirects=False)
                self.assertEqual(
                    response.headers.get("x-robots-tag"),
                    "noindex, nofollow",
                    f"{path} was not noindexed (status {response.status_code})",
                )

    def test_dynamic_lead_bot_subroutes_are_noindexed_even_though_bare_lead_bot_is_public(self):
        bare = self.client.get("/lead-bot")
        self.assertIsNone(bare.headers.get("x-robots-tag"))

        sub = self.client.get("/lead-bot/live-status/does-not-exist", follow_redirects=False)
        self.assertEqual(sub.headers.get("x-robots-tag"), "noindex, nofollow")

    def test_static_assets_are_never_noindexed(self):
        response = self.client.get("/static/logo.png")
        self.assertIsNone(response.headers.get("x-robots-tag"))

    def test_a_brand_new_unlisted_dynamic_route_is_noindexed_by_default(self):
        """The middleware is deny-listed on the public allowlist, not an
        allow-list of known private routes -- so a route this test suite
        has never heard of is still noindexed just by not being public."""
        response = self.client.get("/some/totally/new/route/nobody/registered", follow_redirects=False)
        self.assertEqual(response.headers.get("x-robots-tag"), "noindex, nofollow")


class RobotsTxtTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.client = TestClient(appmain.app)

    def test_robots_txt_returns_200_plain_text(self):
        response = self.client.get("/robots.txt")
        self.assertEqual(response.status_code, 200)
        self.assertIn("text/plain", response.headers.get("content-type", ""))

    def test_robots_txt_references_the_sitemap(self):
        body = self.client.get("/robots.txt").text
        self.assertIn("Sitemap: https://leadmeleads.com/sitemap.xml", body)

    def test_robots_txt_does_not_disallow_the_three_public_pages(self):
        body = self.client.get("/robots.txt").text
        lines = [line.strip() for line in body.splitlines() if line.strip().lower().startswith("disallow:")]
        for path in seo_meta.PUBLIC_INDEXABLE_PATHS:
            for line in lines:
                disallowed_prefix = line.split(":", 1)[1].strip()
                self.assertFalse(
                    path == disallowed_prefix or (disallowed_prefix and path.startswith(disallowed_prefix) and disallowed_prefix != "/"),
                    f"robots.txt line {line!r} would block public page {path!r}",
                )

    def test_robots_txt_does_not_disallow_static_assets(self):
        body = self.client.get("/robots.txt").text
        self.assertNotIn("Disallow: /static", body)

    def test_robots_txt_disallows_known_private_prefixes(self):
        body = self.client.get("/robots.txt").text
        for expected in [
            "Disallow: /login",
            "Disallow: /settings",
            "Disallow: /history",
            "Disallow: /admin",
            "Disallow: /lead-bot/",
            "Disallow: /reports/",
        ]:
            self.assertIn(expected, body)

    def test_robots_txt_exposes_no_secrets_or_filesystem_paths(self):
        body = self.client.get("/robots.txt").text
        for forbidden in ["/home/", "/var/www", ".env", "DATAFORSEO", "SECRET", "PASSWORD"]:
            self.assertNotIn(forbidden, body)


class SitemapXmlTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.client = TestClient(appmain.app)

    def test_sitemap_returns_200_xml(self):
        response = self.client.get("/sitemap.xml")
        self.assertEqual(response.status_code, 200)
        self.assertIn("xml", response.headers.get("content-type", ""))

    def test_sitemap_contains_exactly_the_intended_pages(self):
        body = self.client.get("/sitemap.xml").text
        urls = re.findall(r"<loc>([^<]+)</loc>", body)
        self.assertEqual(
            set(urls),
            {
                "https://leadmeleads.com/",
                "https://leadmeleads.com/lead-bot",
                "https://leadmeleads.com/compare",
                "https://leadmeleads.com/what-makes-a-good-lead",
                "https://leadmeleads.com/how-to-find-local-leads",
                "https://leadmeleads.com/local-lead-generation",
                "https://leadmeleads.com/lead-list-vs-lead-finder",
                "https://leadmeleads.com/resources",
            },
        )
        self.assertEqual(len(urls), 8)

    def test_sitemap_has_no_fabricated_lastmod(self):
        body = self.client.get("/sitemap.xml").text
        self.assertNotIn("<lastmod>", body)

    def test_sitemap_urls_match_public_indexable_paths_constant(self):
        """Locks sitemap.xml to the same single source of truth used by
        the noindex middleware, so they can never silently drift apart."""
        body = self.client.get("/sitemap.xml").text
        urls = set(re.findall(r"<loc>([^<]+)</loc>", body))
        expected = {seo_meta.canonical_url(path) for path in seo_meta.PUBLIC_INDEXABLE_PATHS}
        self.assertEqual(urls, expected)


